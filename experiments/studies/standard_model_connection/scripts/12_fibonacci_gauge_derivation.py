# Fibonacci sequence
def fib(n: int) -> int:
    """Fibonacci: F(1)=1, F(2)=1, F(3)=2, F(4)=3, F(5)=5, F(6)=8, F(7)=13..."""
    if n <= 0:
        return 0
    elif n <= 2:
        return 1
    a, b = 1, 1
    for _ in range(n - 2):
        a, b = b, a + b
    return b


