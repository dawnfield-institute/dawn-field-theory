#!/usr/bin/env python3
"""Block B calibration — CONTROLS ONLY, per the DRAFT protocol.
Computes candidate-functional s-profiles on non-golden trees. Golden diagrams
(A4/D6/E8 and the golden paths 4,5) are NOT touched here: thresholds get sealed
from this data before any golden run. Functionals: (a) spectral gap, (b) mean
first-passage time (exact, via fundamental matrix), (c) stationary entropy proxy."""
import json, numpy as np
from pathlib import Path

def M_of(n, edges, s):
    A = np.zeros((n, n))
    for i, j in edges: A[i, j] = A[j, i] = 1
    D = np.diag(A.sum(1))
    return (D - A) + s * (2*np.eye(n) - D)

def gap(M):
    ev = np.linalg.eigvalsh(M)
    return ev[0] if ev[0] > 1e-12 else ev[1]          # smallest (nonzero) mode

def mfpt(n, edges, s):
    """Mean first-passage time to vertex 0 of the diffusion generated by M(s):
    continuous-time chain with generator -M(s) restricted (Dirichlet at target)."""
    M = M_of(n, edges, s)
    sub = np.delete(np.delete(M, 0, 0), 0, 1)
    try:
        return float(np.linalg.solve(sub, np.ones(n-1)).mean())
    except np.linalg.LinAlgError:
        return np.nan

def ent_proxy(n, edges, s):
    """log det' M(s): stationary Gaussian entropy (up to constants) of dx = -Mx + noise."""
    ev = np.linalg.eigvalsh(M_of(n, edges, s))
    ev = ev[ev > 1e-10]
    return float(-0.5*np.sum(np.log(ev)))

CONTROLS = {
  "path3":  (3, [(0,1),(1,2)]),
  "path6":  (6, [(i,i+1) for i in range(5)]),
  "path7":  (7, [(i,i+1) for i in range(6)]),
  "D5":     (5, [(0,1),(1,2),(2,3),(2,4)]),
  "E6":     (6, [(0,1),(1,2),(2,3),(3,4),(2,5)]),
  "E7":     (7, [(i,i+1) for i in range(5)]+[(2,6)]),
  "star6":  (6, [(0,k) for k in range(1,6)]),
  "rand8a": (8, [(0,1),(1,2),(1,3),(3,4),(3,5),(5,6),(5,7)]),
  "rand8b": (8, [(0,1),(0,2),(2,3),(2,4),(4,5),(4,6),(6,7)]),
}
S = np.round(np.arange(0.0, 2.01, 0.05), 3)
out = {}
print(f"{'tree':<8} {'argmax gap':>11} {'argmin MFPT':>12} {'argmax ent':>11}")
for name, (n, e) in CONTROLS.items():
    g  = [gap(M_of(n, e, s)) for s in S]
    f  = [mfpt(n, e, s) for s in S]
    en = [ent_proxy(n, e, s) for s in S]
    r = {"argmax_gap": float(S[int(np.nanargmax(g))]),
         "argmin_mfpt": float(S[int(np.nanargmin(f))]),
         "argmax_ent": float(S[int(np.nanargmax(en))])}
    out[name] = r
    print(f"{name:<8} {r['argmax_gap']:>11} {r['argmin_mfpt']:>12} {r['argmax_ent']:>11}")
at1 = {k: sum(abs(v[c]-1.0) < 0.051 for c in v) for k, v in out.items()}
print("\ncontrols optimizing at s=1 (of 3 functionals):", at1)
print("VERDICT GUIDE: functionals where CONTROLS peak at s=1 are GENERIC -> inadmissible.")
Path(__file__).parent.parent.joinpath("results","exp_04_calibration_20260831.json").write_text(json.dumps(out, indent=1))
