"""
Experiment 12: Cramér Random Model Comparison

Compares real prime eigenvalue structure to synthetic "random primes"
generated by the Cramér model (each n>2 is prime with probability 1/log(n)).

Key question: Does the φ-structure disappear in random primes?
If yes, it proves φ is intrinsic to REAL prime distribution.
"""

import sys
import json
from pathlib import Path
from datetime import datetime

sys.path.insert(0, str(Path(__file__).parent.parent / 'core'))

from prime_chords import (
    get_primes, compute_gaps, extract_chords,
    build_transition_matrix, compute_eigenvalues, PHI_INV
)
import numpy as np
from collections import Counter


def generate_cramer_primes(limit: int, seed: int = None) -> np.ndarray:
    """
    Generate synthetic primes using Cramér's random model.
    
    Each integer n > 2 is "prime" with probability 1/log(n).
    Always includes 2 as prime.
    """
    rng = np.random.default_rng(seed)
    
    primes = [2]
    for n in range(3, limit):
        prob = 1 / np.log(n)
        if rng.random() < prob:
            primes.append(n)
    
    return np.array(primes, dtype=float)


def analyze_prime_sequence(primes: np.ndarray, topK: int = 25):
    """Compute eigenvalues and statistics for a prime sequence."""
    if len(primes) < 100:
        return None
    
    gaps = np.diff(primes)
    chords = extract_chords(gaps, n_gaps=2)
    P, top_chords = build_transition_matrix(chords, top_k=topK)
    eigenvals = compute_eigenvalues(P[:topK, :topK])
    
    # Motif analysis
    counts = Counter([tuple(c) for c in chords])
    
    # Check palindrome enrichment
    palindromes = [(4,2,4), (6,4,6), (2,10,2), (6,8,6)]
    pal_count = sum(counts.get(p, 0) for p in palindromes)
    
    return {
        'n_primes': len(primes),
        'n_gaps': len(gaps),
        'n_unique_chords': len(counts),
        'lambda1': float(eigenvals[0]) if len(eigenvals) > 0 else 0,
        'lambda2': float(eigenvals[1]) if len(eigenvals) > 1 else 0,
        'eigenvalues': eigenvals[:10].tolist(),
        'palindrome_count': pal_count,
        'gap_mean': float(np.mean(gaps)),
        'gap_std': float(np.std(gaps)),
    }


def run_experiment(prime_limit: int = 500000, n_trials: int = 20):
    """Run Cramér random model comparison."""
    
    print("=" * 70)
    print("PRIME HARMONIC MANIFOLD: Cramér Random Model Comparison")
    print("=" * 70)
    
    # Real primes
    print(f"\nAnalyzing REAL primes up to {prime_limit:,}...")
    real_primes = get_primes(prime_limit)
    real_stats = analyze_prime_sequence(real_primes)
    
    print(f"  Real primes: {real_stats['n_primes']:,}")
    print(f"  Real λ₁: {real_stats['lambda1']:.6f}")
    print(f"  Real λ₂: {real_stats['lambda2']:.6f}")
    print(f"  Reference 1/φ: {PHI_INV:.6f}")
    print(f"  Deviation: {real_stats['lambda1'] - PHI_INV:+.6f}")
    
    # Cramér random primes
    print(f"\nGenerating {n_trials} Cramér random prime sequences...")
    
    cramer_results = []
    cramer_lambda1s = []
    
    for trial in range(n_trials):
        cramer_primes = generate_cramer_primes(prime_limit, seed=trial)
        stats = analyze_prime_sequence(cramer_primes)
        
        if stats:
            cramer_results.append(stats)
            cramer_lambda1s.append(stats['lambda1'])
            
            if trial < 5 or trial == n_trials - 1:
                print(f"  Trial {trial+1}: {stats['n_primes']:,} primes, λ₁ = {stats['lambda1']:.6f}")
    
    print(f"\n" + "-" * 60)
    print("COMPARISON: REAL vs CRAMÉR")
    print("-" * 60)
    
    cramer_mean_l1 = np.mean(cramer_lambda1s)
    cramer_std_l1 = np.std(cramer_lambda1s)
    
    print(f"\n  {'Metric':<25} {'Real':<15} {'Cramér (mean±std)':<20}")
    print("  " + "-" * 60)
    print(f"  {'λ₁':<25} {real_stats['lambda1']:<15.6f} {cramer_mean_l1:.6f} ± {cramer_std_l1:.4f}")
    print(f"  {'λ₂':<25} {real_stats['lambda2']:<15.6f} {np.mean([r['lambda2'] for r in cramer_results]):.6f}")
    print(f"  {'Unique chords':<25} {real_stats['n_unique_chords']:<15} {np.mean([r['n_unique_chords'] for r in cramer_results]):.0f}")
    print(f"  {'Gap mean':<25} {real_stats['gap_mean']:<15.2f} {np.mean([r['gap_mean'] for r in cramer_results]):.2f}")
    print(f"  {'Gap std':<25} {real_stats['gap_std']:<15.2f} {np.mean([r['gap_std'] for r in cramer_results]):.2f}")
    print(f"  {'Palindromes':<25} {real_stats['palindrome_count']:<15} {np.mean([r['palindrome_count'] for r in cramer_results]):.0f}")
    
    # Statistical test: Is real λ₁ significantly different from Cramér?
    print(f"\n" + "-" * 60)
    print("STATISTICAL SIGNIFICANCE")
    print("-" * 60)
    
    z_score = (real_stats['lambda1'] - cramer_mean_l1) / cramer_std_l1 if cramer_std_l1 > 0 else 0
    
    print(f"\n  Real λ₁ = {real_stats['lambda1']:.6f}")
    print(f"  Cramér λ₁ = {cramer_mean_l1:.6f} ± {cramer_std_l1:.4f}")
    print(f"  Z-score = {z_score:.2f}")
    
    significant = abs(z_score) > 2.0
    print(f"  Significant difference (|z| > 2): {'YES' if significant else 'NO'}")
    
    # Is Cramér λ₁ close to 1/φ?
    cramer_phi_error = abs(cramer_mean_l1 - PHI_INV)
    real_phi_error = abs(real_stats['lambda1'] - PHI_INV)
    
    print(f"\n  Distance to 1/φ:")
    print(f"    Real: {real_phi_error:.6f}")
    print(f"    Cramér: {cramer_phi_error:.6f}")
    print(f"    Real is {'CLOSER' if real_phi_error < cramer_phi_error else 'FARTHER'} to 1/φ")
    
    # Key insight
    print(f"\n" + "=" * 70)
    print("KEY FINDING")
    print("=" * 70)
    
    if significant and real_phi_error < cramer_phi_error:
        conclusion = "PHI_STRUCTURE_INTRINSIC"
        print("""
  The φ-structure is INTRINSIC to real primes:
  - Real primes have λ₁ significantly closer to 1/φ than Cramér model
  - Random primes with same density do NOT reproduce φ-eigenvalue
  - This proves the structure comes from NUMBER-THEORETIC constraints,
    not just the density law 1/log(n)
""")
    elif not significant:
        conclusion = "NO_DIFFERENCE"
        print("""
  Cannot distinguish real from Cramér:
  - Real and random primes have similar λ₁
  - The φ-structure may be a statistical artifact of density
  - More investigation needed
""")
    else:
        conclusion = "DIFFERENT_BUT_NOT_PHI"
        print("""
  Real differs from Cramér, but not due to φ:
  - Significant difference exists
  - But Cramér is actually closer to 1/φ (unexpected)
  - Need to investigate further
""")
    
    # Save results
    results = {
        'experiment': 'exp_12_cramer_comparison',
        'timestamp': datetime.now().isoformat(),
        'parameters': {
            'prime_limit': prime_limit,
            'n_trials': n_trials,
        },
        'results': {
            'real': real_stats,
            'cramer': {
                'n_trials': len(cramer_results),
                'mean_lambda1': cramer_mean_l1,
                'std_lambda1': cramer_std_l1,
                'mean_lambda2': float(np.mean([r['lambda2'] for r in cramer_results])),
                'all_lambda1': cramer_lambda1s,
            },
            'comparison': {
                'z_score': float(z_score),
                'significant': bool(significant),
                'real_phi_error': float(real_phi_error),
                'cramer_phi_error': float(cramer_phi_error),
            },
        },
        'conclusion': conclusion
    }
    
    results_dir = Path(__file__).parent.parent / 'results'
    results_dir.mkdir(exist_ok=True)
    
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    results_file = results_dir / f'exp_12_cramer_comparison_{timestamp}.json'
    
    with open(results_file, 'w') as f:
        json.dump(results, f, indent=2)
    
    print(f"\n✓ Results saved to {results_file}")
    
    return results


if __name__ == '__main__':
    run_experiment()
