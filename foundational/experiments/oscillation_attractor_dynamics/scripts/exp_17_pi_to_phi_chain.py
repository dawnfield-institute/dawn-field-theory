def correlation_analysis(N: int = 50000) -> Dict:
    """
    Across many random sequences, test:
    Does high π-coherence correlate with φ emergence in SEC?
    """
    n_trials = 20
    
    coherences = []
    phi_errors = []
    
    for trial in range(n_trials):
        # Random modulation parameter
        theta = np.random.uniform(0.5, 10.0)
        amplitude = np.random.uniform(0.5, 2.0)
        
        # Generate sequence
        n = np.arange(1, N + 1).astype(float)
        signal = amplitude * np.sin(theta * n) * np.cos(theta * np.log(n + 1))
        signal = (signal - signal.min()) / (signal.max() - signal.min() + 1e-10)
        seq = (signal > 0.5).astype(int)
        
        # Measure π-coherence
        pi_coh = pi_coherence_of_sequence(seq)
        
        # Run SEC (quick version - fewer lambdas)
        lambdas = np.linspace(0.95, 0.999, 20)
        sec_result = run_sec_analysis(seq, f"trial_{trial}", lambdas)
        
        coherences.append(pi_coh)
        phi_errors.append(sec_result['best_error'])
    
    # Compute correlation
    corr = np.corrcoef(coherences, phi_errors)[0, 1]
    
    return {
        'coherences': coherences,
        'phi_errors': phi_errors,
        'correlation': corr,
        'interpretation': 'High π-coherence → low φ-error' if corr < 0 else 'No clear relationship'
    }

