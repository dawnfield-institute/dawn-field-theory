def sieve_primes(n: int) -> np.ndarray:
    """Sieve of Eratosthenes"""
    is_prime = np.ones(n + 1, dtype=bool)
    is_prime[0:2] = False
    for i in range(2, int(np.sqrt(n)) + 1):
        if is_prime[i]:
            is_prime[i*i::i] = False
    return np.where(is_prime)[0]

def compute_sec(sequence: np.ndarray, lambda_decay: float = 0.95, 
                window: int = 101) -> Tuple[np.ndarray, np.ndarray]:
    """
    Compute SEC dynamics on a binary sequence.
    
    Returns:
        I: Impulse array (local information injection)
        E: Stress field (accumulated impulse with decay)
    """
    N = len(sequence)
    I = np.zeros(N)
    E = np.zeros(N)
    
    half_window = window // 2
    
    for n in range(half_window, N - half_window):
        # Local window
        local = sequence[n - half_window:n + half_window + 1]
        
        # Impulse: deviation from local mean
        local_mean = np.mean(local)
        I[n] = sequence[n] - local_mean
        
        # Stress accumulation with decay
        if n > 0:
            E[n] = lambda_decay * E[n-1] + I[n]
    
    return I, E

def measure_phi_fraction(E: np.ndarray, skip_transient: int = 1000) -> float:
    """
    Measure the fraction of positive stress values.
    
    At SEC criticality, this should converge to 1/φ ≈ 0.618.
    """
    E_valid = E[skip_transient:]
    E_valid = E_valid[E_valid != 0]  # Remove zeros
    
    if len(E_valid) == 0:
        return 0.5
    
    return np.mean(E_valid > 0)

def generate_prime_indicator(N: int) -> np.ndarray:
    """Generate binary sequence: 1 if n is prime, 0 otherwise."""
    primes = set(sieve_primes(N))
    return np.array([1 if n in primes else 0 for n in range(N)])

def generate_zero_modulated_sequence(N: int, num_zeros: int = 20, 
                                     threshold: float = 0.5) -> np.ndarray:
    """
    Generate a sequence modulated by Riemann zero oscillations.
    
    Simulates what primes "would look like" if generated by zero superposition.
    """
    n = np.arange(1, N + 1).astype(float)
    
    # Superposition of oscillations from zeros
    signal = np.zeros(N)
    for gamma in RIEMANN_ZEROS[:num_zeros]:
        # Each zero contributes an oscillation in log space
        signal += np.cos(gamma * np.log(n)) / np.sqrt(gamma)
    
    # Normalize to [0, 1] range
    signal = (signal - signal.min()) / (signal.max() - signal.min() + 1e-10)
    
    # Threshold to binary
    binary = (signal > threshold).astype(int)
    
    return binary

def generate_pi_modulated_sequence(N: int, threshold: float = 0.5) -> np.ndarray:
    """
    Generate sequence with π-modulation (as found in exp_15).
    """
    n = np.arange(1, N + 1).astype(float)
    
    # π-modulated oscillation
    signal = np.sin(PI * n) * np.sin(PI * np.sqrt(n)) * np.cos(PI * np.log(n + 1))
    
    # Normalize
    signal = (signal - signal.min()) / (signal.max() - signal.min() + 1e-10)
    
    return (signal > threshold).astype(int)

def generate_random_sparse_sequence(N: int, density: float = 0.1) -> np.ndarray:
    """Generate random sequence with similar density to primes."""
    return (np.random.random(N) < density).astype(int)

def generate_phi_resonant_sequence(N: int) -> np.ndarray:
    """
    Generate sequence with φ-based structure.
    
    If φ is the output, does putting φ in the input change things?
    """
    n = np.arange(1, N + 1).astype(float)
    
    # Fibonacci-like oscillation
    signal = np.sin(n / PHI) * np.cos(n * PHI_INV)
    signal += np.sin(n * PHI_INV * PI)
    
    # Normalize
    signal = (signal - signal.min()) / (signal.max() - signal.min() + 1e-10)
    
    # Threshold at 1/φ
    return (signal > PHI_INV).astype(int)

def run_sec_analysis(sequence: np.ndarray, name: str, 
                     lambdas: np.ndarray = None) -> Dict:
    """
    Run SEC analysis and find the λ* where frac → 1/φ.
    """
    if lambdas is None:
        lambdas = np.linspace(0.90, 0.999, 50)
    
    results = []
    
    for lam in lambdas:
        I, E = compute_sec(sequence, lambda_decay=lam)
        frac = measure_phi_fraction(E)
        error = abs(frac - PHI_INV)
        
        results.append({
            'lambda': lam,
            'frac': frac,
            'error': error
        })
    
    # Find optimal λ
    best = min(results, key=lambda x: x['error'])
    
    return {
        'name': name,
        'results': results,
        'best_lambda': best['lambda'],
        'best_frac': best['frac'],
        'best_error': best['error'],
        'reaches_phi': best['error'] < 0.01  # Within 1% of 1/φ
    }

def pi_coherence_of_sequence(sequence: np.ndarray) -> float:
    """
    Measure the π-coherence of a binary sequence.
    
    Uses the metric from exp_15: variance of Möbius-weighted oscillation.
    """
    N = len(sequence)
    n = np.arange(1, N + 1).astype(float)
    
    # Treat sequence as pseudo-Möbius (1 → +1, 0 → -1 or 0)
    pseudo_mu = 2 * sequence - 1  # Map 0,1 to -1,+1
    
    # π-modulated sum at σ = 0.5
    weights = 1.0 / np.sqrt(n)
    terms = pseudo_mu * np.exp(1j * PI * n) * weights
    cumsum = np.cumsum(terms)
    
    # Variance of second half (lower = more coherent)
    half = len(cumsum) // 2
    variance = np.var(np.abs(cumsum[half:]))
    
    return variance

